class LegendreDuality:
    """
    Compute Legendre primal ψ and dual ψ* for the ACF exponential family.

       ψ(c) = log Z(c)              [log-partition, primal coords]
       η(c) = ∇_c ψ(c)             [moment parameters]
       ψ*(η) = c^T η - ψ(c)        [entropy / Legendre conjugate]
       KL(η‖c) = ψ(c) + ψ*(η) - c^T η  [should be 0 on dual curve]
    """

    def __init__(self, fisher_metric: FisherMetricACF):
        self.fisher = fisher_metric

    def compute_at(
        self,
        c: torch.Tensor,
        domain: Tuple[float, float] = (-1.0, 1.0),
    ) -> LegendrePoint:
        psi = self.fisher.log_partition(c, domain)
        eta = self.fisher.expected_observable(c, domain)

        c_f = c.to(torch.float64)
        eta_f = eta.to(torch.float64)
        psi_star = float((c_f @ eta_f).item()) - psi
        kl = psi + psi_star - float((c_f @ eta_f).item())

        return LegendrePoint(
            theta=c,
            eta=eta,
            psi=psi,
            psi_star=psi_star,
            kl_diverg=abs(kl),  # should be ≈ 0 on the dual curve
        )


