def polynomial_observables(max_degree: int = 4) -> List[Callable[[torch.Tensor], torch.Tensor]]:
    """Standard polynomial observable basis {1, x, x², ..., x^n}."""
    obs = [lambda x, _k=k: x ** _k for k in range(max_degree + 1)]
    return obs


def fourier_observables(n_harmonics: int = 3) -> List[Callable[[torch.Tensor], torch.Tensor]]:
    """Fourier observable basis {1, cos(x), sin(x), cos(2x), sin(2x), ...}."""
    obs: List[Callable] = [lambda x: torch.ones_like(x)]
    for k in range(1, n_harmonics + 1):
        obs.append(lambda x, _k=k: torch.cos(_k * x))
        obs.append(lambda x, _k=k: torch.sin(_k * x))
    return obs
