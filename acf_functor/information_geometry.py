class DualityVerifier:
    """
    Verify that g_F ≈ g_A at test points on the ACF reduction manifold.

    The core check: compute both metrics at the same parameter point θ
    and measure their Frobenius distance.
    """

    def __init__(
        self,
        fisher_metric: FisherMetricACF,
        affine_metric: AffineMetricACF,
        threshold: float = 0.5,       # relative error threshold for duality
    ):
        self.fisher = fisher_metric
        self.affine = affine_metric
        self.threshold = threshold

    def verify(
        self,
        c: torch.Tensor,               # FMA coefficient vector
        K: Optional[torch.Tensor] = None,  # Koopman matrix (None → diag from c)
        domain: Tuple[float, float] = (-1.0, 1.0),
        test_gradient: Optional[torch.Tensor] = None,
    ) -> DualityVerificationResult:
        """
        Compute both metrics and compare.
        """
        G_F_obj = self.fisher.compute(c, domain)
        G_F = G_F_obj.G

        if K is None:
            # Build proxy PD matrix from c: K = diag(|c| + ε)
            K_proxy = torch.diag(torch.abs(c.to(torch.float64)) + 1e-3)
        else:
            K_proxy = K.to(torch.float64)

        G_A_obj = self.affine.compute(K_proxy)
        G_A = G_A_obj.G

        # Align sizes (take min dimension)
        d = min(G_F.shape[0], G_A.shape[0])
        GF = G_F[:d, :d]
        GA = G_A[:d, :d]

        frob = float(torch.norm(GF - GA, p="fro").item())
        gf_norm = float(torch.norm(GF, p="fro").item())
        rel_err = frob / (gf_norm + 1e-30)
        duality_holds = rel_err < self.threshold

        # Natural gradient comparison
        if test_gradient is None:
            test_gradient = torch.randn(d, dtype=torch.float64)
        g_test = test_gradient[:d].to(torch.float64)

        # Fisher natural gradient: G_F^{-1} g
        try:
            ng_fisher = torch.linalg.solve(GF + 1e-8 * torch.eye(d, dtype=torch.float64), g_test)
        except Exception:
            ng_fisher = g_test.clone()

        # Affine natural gradient: K_proxy · g
        ng_affine = self.affine.natural_gradient(g_test, K_proxy[:d, :d])

        ng_err = float(torch.norm(ng_fisher - ng_affine).item())
        ng_norm = float(torch.norm(ng_fisher).item())
        ngrel = ng_err / (ng_norm + 1e-30)

        return DualityVerificationResult(
            fisher_metric=G_F_obj,
            affine_metric=G_A_obj,
            frobenius_distance=frob,
            relative_error=rel_err,
            duality_holds=duality_holds,
            natural_gradient_error=ng_err,
            corollary_verified=(ngrel < 1.0),  # same order of magnitude
        )


