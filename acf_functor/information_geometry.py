@dataclass
class MetricTensor:
    """Riemannian metric tensor at a point on the ACF manifold."""
    G: torch.Tensor          # the metric matrix (d×d)
    kind: str                # "fisher" | "affine"
    condition_number: float  # numerical condition
    log_det: float           # log|G|


@dataclass
class LegendrePoint:
    """Point in the dual coordinate system."""
    theta: torch.Tensor      # natural parameters (c, the FMA coefficients)
    eta: torch.Tensor        # expectation (moment) parameters
    psi: float               # log-partition ψ(θ) = log Z(c)
    psi_star: float          # Legendre conjugate ψ*(η)
    kl_diverg: float         # KL(η ‖ θ) as duality gap


@dataclass
class DualityVerificationResult:
    """Verification that g_F ≈ g_A at a test point."""
    fisher_metric: MetricTensor
    affine_metric: MetricTensor
    frobenius_distance: float      # ‖G_F - G_A‖_F
    relative_error: float          # ‖G_F - G_A‖_F / ‖G_F‖_F
    duality_holds: bool            # relative_error < threshold
    natural_gradient_error: float  # ‖∇_F - ∇_A‖_2 on a test gradient
    corollary_verified: bool       # SGD-natural ≈ ACF-natural


@dataclass
class InformationGeometryReport:
    theta: torch.Tensor                # FMA coefficient vector
    g_fisher: MetricTensor
    g_affine: MetricTensor
    legendre_point: LegendrePoint
    duality: DualityVerificationResult
    natural_gradient_fisher: torch.Tensor
    natural_gradient_affine: torch.Tensor
    fma_energy_geometric: float        # E(f) from geometric (volume) perspective


# ---------------------------------------------------------------------------
# Fisher-Rao metric computation
# ---------------------------------------------------------------------------

class FisherMetricACF:
    """
    Fisher-Rao metric on the exponential family generated by FMA observables.

    Model: p(x | c) ∝ exp(c^T ψ(x))
    where ψ(x) = [ψ_1(x), ..., ψ_d(x)] is the Koopman observable basis.

    Fisher metric: G_F(c) = Cov_{p(·|c)}[ψ(x)] = E[ψψ^T] - E[ψ]E[ψ]^T
    """

    def __init__(
        self,
        observable_fns: List[Callable[[torch.Tensor], torch.Tensor]],
        n_samples: int = 2000,
        dtype: torch.dtype = torch.float64,
    ):
        self.observables = observable_fns
        self.n_samples = n_samples
        self.dtype = dtype
        self.d = len(observable_fns)

    def compute(
        self,
        c: torch.Tensor,                           # d-dim parameter vector
        domain: Tuple[float, float] = (-1.0, 1.0),
    ) -> MetricTensor:
        """Compute G_F = Cov_p[ψ(x)] at parameter c."""
        x = torch.linspace(domain[0], domain[1], self.n_samples, dtype=self.dtype)
        Psi = self._stack_observables(x)           # (d, n_samples)

        # Unnormalized weights: w_i ∝ exp(c^T ψ(x_i))
        log_w = c.to(self.dtype) @ Psi             # (n_samples,)
        log_w = log_w - log_w.max()                # stabilize
        w = torch.exp(log_w)
        w = w / w.sum()                            # normalize

        # Weighted mean and covariance
        E_psi = (Psi * w.unsqueeze(0)).sum(dim=1)   # (d,)
        diff = Psi - E_psi.unsqueeze(1)             # (d, n_samples)
        G_F = (diff * w.unsqueeze(0)) @ diff.T      # (d, d)
        G_F = 0.5 * (G_F + G_F.T)                  # symmetrize

        return self._to_metric_tensor(G_F, "fisher")

    def log_partition(
        self,
        c: torch.Tensor,
        domain: Tuple[float, float] = (-1.0, 1.0),
    ) -> float:
        """ψ(c) = log Z(c) = log ∫ exp(c^T ψ(x)) dx  (numerically)."""
        x = torch.linspace(domain[0], domain[1], self.n_samples, dtype=self.dtype)
        Psi = self._stack_observables(x)
        log_w = c.to(self.dtype) @ Psi
        return float((torch.logsumexp(log_w, dim=0) + math.log((domain[1]-domain[0])/self.n_samples)).item())

    def expected_observable(
        self,
        c: torch.Tensor,
        domain: Tuple[float, float] = (-1.0, 1.0),
    ) -> torch.Tensor:
        """η = E_{p(·|c)}[ψ(x)]  (moment parameters)."""
        x = torch.linspace(domain[0], domain[1], self.n_samples, dtype=self.dtype)
        Psi = self._stack_observables(x)
        log_w = c.to(self.dtype) @ Psi
        log_w = log_w - log_w.max()
        w = torch.exp(log_w)
        w = w / w.sum()
        return (Psi * w.unsqueeze(0)).sum(dim=1)

    def _stack_observables(self, x: torch.Tensor) -> torch.Tensor:
        rows = []
        for psi in self.observables:
            try:
                y = psi(x)
                rows.append(y.unsqueeze(0) if y.dim() == 1 else y[:1])
            except Exception:
                rows.append(torch.zeros(1, x.numel(), dtype=self.dtype))
        return torch.cat(rows, dim=0)  # (d, n)

    def _to_metric_tensor(self, G: torch.Tensor, kind: str) -> MetricTensor:
        try:
            sv = torch.linalg.svdvals(G)
            cond = float((sv[0] / (sv[-1] + 1e-30)).item()) if sv.numel() > 0 else float("inf")
            log_det = float(torch.sum(torch.log(sv + 1e-300)).item())
        except Exception:
            cond = float("inf")
            log_det = float("-inf")
        return MetricTensor(G=G, kind=kind, condition_number=cond, log_det=log_det)


