class InformationGeometry:
    """
    Central API for ACF Information Geometry analysis.

    Computes and reports:
    - Fisher metric g_F at a parameter point
    - Affine (Lie) metric g_A at the same point
    - Legendre duality (ψ, ψ*, KL gap)
    - Natural gradients from both perspectives
    - Verification that they agree (duality theorem)
    - FMA energy from the geometric (volume) viewpoint
    """

    def __init__(
        self,
        observable_fns: List[Callable[[torch.Tensor], torch.Tensor]],
        n_samples: int = 2000,
        dtype: torch.dtype = torch.float64,
    ):
        self.fisher_metric = FisherMetricACF(observable_fns, n_samples, dtype)
        self.affine_metric = AffineMetricACF(dtype)
        self.legendre = LegendreDuality(self.fisher_metric)
        self.verifier = DualityVerifier(self.fisher_metric, self.affine_metric)
        self.dtype = dtype

    def analyze(
        self,
        fma_coefficients: torch.Tensor,    # θ = FMA coefficient vector
        koopman_matrix: Optional[torch.Tensor] = None,
        domain: Tuple[float, float] = (-1.0, 1.0),
    ) -> InformationGeometryReport:
        c = fma_coefficients.to(self.dtype)

        g_f = self.fisher_metric.compute(c, domain)
        K = koopman_matrix.to(self.dtype) if koopman_matrix is not None else torch.diag(torch.abs(c) + 1e-3)
        g_a = self.affine_metric.compute(K)
        leg = self.legendre.compute_at(c, domain)
        dual = self.verifier.verify(c, K, domain)

        # Natural gradients (test gradient = c itself, for concreteness)
        g_raw = c.clone()
        d_min = min(g_f.G.shape[0], c.numel())
        G_F_use = g_f.G[:d_min, :d_min]
        try:
            ng_fisher = torch.linalg.solve(
                G_F_use + 1e-8 * torch.eye(d_min, dtype=self.dtype), g_raw[:d_min]
            )
        except Exception:
            ng_fisher = g_raw[:d_min]
        ng_affine = self.affine_metric.natural_gradient(g_raw[:d_min], K[:d_min, :d_min])

        # Geometric FMA energy: log-volume of the metric ball
        e_geometric = abs(g_f.log_det) / (2.0 * max(math.log(2), 1.0))

        return InformationGeometryReport(
            theta=c,
            g_fisher=g_f,
            g_affine=g_a,
            legendre_point=leg,
            duality=dual,
            natural_gradient_fisher=ng_fisher,
            natural_gradient_affine=ng_affine,
            fma_energy_geometric=e_geometric,
        )

    def summary(self, report: InformationGeometryReport) -> str:
        d = report.duality
        return (
            f"ACF Information Geometry Report\n"
            f"{'='*50}\n"
            f"Fisher metric:  cond={d.fisher_metric.condition_number:.2e}, "
            f"log|G_F|={d.fisher_metric.log_det:.3f}\n"
            f"Affine metric:  cond={d.affine_metric.condition_number:.2e}, "
            f"log|G_A|={d.affine_metric.log_det:.3f}\n"
            f"Duality: ‖G_F - G_A‖_F / ‖G_F‖_F = {d.relative_error:.3f} "
            f"{'✓ HOLDS' if d.duality_holds else '✗ FAILS'}\n"
            f"KL gap (duality gap) = {report.legendre_point.kl_diverg:.3e}  "
            f"(should be ≈ 0)\n"
            f"‖∇_Fisher - ∇_Affine‖ = {d.natural_gradient_error:.3e}  "
            f"{'✓ corollary verified' if d.corollary_verified else '✗ corollary fails'}\n"
            f"Geometric FMA energy E(f) ≈ {report.fma_energy_geometric:.3f}\n"
            f"\nCorollary: 'Training with natural gradient = ACF compilation'  "
            f"{'✓' if d.corollary_verified else '✗'}"
        )


