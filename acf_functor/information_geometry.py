# Affine metric computation (from Lie group structure)
# ---------------------------------------------------------------------------

class AffineMetricACF:
    """
    Affine (Lie group) metric on the ACF reduction manifold.

    The space of d×d EDMD Koopman matrices K_d ∈ GL(d) carries a
    natural left-invariant metric from the Lie group GL(d):

       g_A(K)(U, V) = tr(K^{-1}U · K^{-1}V)

    This is the Fisher metric on the normal distribution with covariance K
    (when K is positive definite), establishing the Legendre duality.

    Parameterized version: θ = vec(K_d), and the metric acts on tangent vectors.
    """

    def __init__(self, dtype: torch.dtype = torch.float64):
        self.dtype = dtype

    def compute(
        self,
        K: torch.Tensor,        # d×d Koopman matrix (or proxy PD matrix)
        regularize: float = 1e-8,
    ) -> MetricTensor:
        """Compute g_A = K^{-1} ⊗ K^{-1} (Kronecker product metric on vec(K))."""
        K = K.to(self.dtype)
        d = K.shape[0]

        # Ensure positive definiteness
        K_pd = K.T @ K + regularize * torch.eye(d, dtype=self.dtype)

        try:
            K_inv = torch.linalg.inv(K_pd)
            # The metric on the tangent space (as a d²×d² matrix) is K_inv ⊗ K_inv
            # For monitoring purposes, we work with the d×d version: G_A = K^{-1}
            G_A = K_inv
        except Exception:
            G_A = torch.eye(d, dtype=self.dtype)

        G_A = 0.5 * (G_A + G_A.T)
        return self._to_metric_tensor(G_A, "affine")

    def natural_gradient(
        self,
        gradient: torch.Tensor,
        K: torch.Tensor,
        regularize: float = 1e-8,
    ) -> torch.Tensor:
        """
        Compute the affine natural gradient: ∇_A = G_A^{-1} ∇ = K ∇.

        This is the Lie-algebraic steepest descent direction.
        """
        K = K.to(self.dtype)
        g = gradient.to(self.dtype)
        K_pd = K.T @ K + regularize * torch.eye(K.shape[0], dtype=self.dtype)
        return K_pd @ g

    def _to_metric_tensor(self, G: torch.Tensor, kind: str) -> MetricTensor:
        try:
            sv = torch.linalg.svdvals(G)
            cond = float((sv[0] / (sv[-1] + 1e-30)).item()) if sv.numel() > 0 else float("inf")
            log_det = float(torch.sum(torch.log(sv + 1e-300)).item())
        except Exception:
            cond = float("inf")
            log_det = float("-inf")
        return MetricTensor(G=G, kind=kind, condition_number=cond, log_det=log_det)


