class ConjectureStatus(Enum):
    PROVED   = "proved"
    PLAUSIBLE = "plausible"
    REFUTED  = "refuted"
    TIMEOUT  = "timeout"
    TAUTOLOGICAL = "tautological"  # rejected by bridge (DEBILIDAD #2)
    ERROR    = "error"


@dataclass
class ACFConjecture:
    """A candidate theorem generated by Genesis."""
    conjecture_id: str
    statement:     str          # Mathematical statement (for humans)
    lean_statement: str         # Lean 4 expression of the statement
    lean_proof:    Optional[str]  # Lean 4 proof script (or None)
    origin:        str          # e.g. "chebyshev_error_bound", "alpha_hardness"
    evidence:      Dict[str, Any]  # empirical data supporting the conjecture
    generated_at:  float = field(default_factory=time.time)


@dataclass
class BridgeVerificationResult:
    """Result of verifying a conjecture through the Lean bridge."""
    conjecture:    ACFConjecture
    status:        ConjectureStatus
    lean_output:   str
    is_tautological: bool
    proof_used:    str          # which tactic/lemma was decisive
    time_s:        float
    error_msg:     Optional[str] = None


@dataclass
class CatalogEntry:
    """An entry in the ACF Theorem Catalog."""
    theorem_id:     str
    statement:      str
    lean_statement: str
    lean_proof:     str
    status:         ConjectureStatus
    origin:         str
    added_at:       float = field(default_factory=time.time)


# ---------------------------------------------------------------------------
# Non-tautology checker (DEBILIDAD #2)
# ---------------------------------------------------------------------------

_TAUTOLOGICAL_PATTERNS = [
    re.compile(r"^\s*exact\s+h\b"),            # exact h
    re.compile(r"^\s*exact\s+h_\w+\b"),        # exact h_bound etc.
    re.compile(r"^\s*assumption\s*$"),          # assumption
    re.compile(r"^\s*rfl\s*$"),                # rfl
    re.compile(r"^\s*simp\s*\[?\s*rfl\s*\]?"), # simp [rfl]
    re.compile(r"^\s*trivial\s*$"),             # trivial
    re.compile(r"^\s*tauto\s*$"),               # tauto
]

_NON_TAUTOLOGICAL_PATTERNS = [
    re.compile(r"\blinarith\b"),
    re.compile(r"\bnorm_num\b"),
    re.compile(r"\bapply\s+\w"),
    re.compile(r"\bhave\b"),
    re.compile(r"\bcalc\b"),
    re.compile(r"\bfield_simp\b"),
    re.compile(r"\bring\b"),
]


def is_tautological(proof: str) -> bool:
    """
    Returns True if the Lean proof is purely tautological
    (i.e., restates a hypothesis or uses rfl without computation).
    """
    lines = [l.strip() for l in proof.strip().splitlines() if l.strip()]
    # A non-empty proof that only has tautological lines
    all_tautological = all(
        any(p.match(ln) for p in _TAUTOLOGICAL_PATTERNS)
        for ln in lines
        if ln and not ln.startswith("--") and not ln.startswith("/-")
    )
    # If ANY non-tautological tactic appears, it's NOT a tautology
    has_real = any(
        p.search(proof) for p in _NON_TAUTOLOGICAL_PATTERNS
    )
    return all_tautological and not has_real


# ---------------------------------------------------------------------------
# Lean template library for common ACF theorems
# ---------------------------------------------------------------------------

class ACFLeanTemplateLibrary:
    """
    Library of Lean 4 proof templates for common ACF theorems.

    Each template takes named parameters and returns a valid Lean 4 block.
    These produce NON-TAUTOLOGICAL proofs using linarith / norm_num / apply.
    """

    @staticmethod
    def chebyshev_error_bound(
        func_name: str,
        degree: int,
        epsilon: float,
        bernstein_rho: float,
    ) -> Tuple[str, str]:
        """
        Theorem: ‖f - P_d‖_∞ ≤ ε for f = func_name at degree d.

        Returns (lean_statement, lean_proof).
        Proof uses norm_num to verify the numerical bound.
        """
        rho_pow_neg_d = bernstein_rho ** (-degree)
        # Conservative: actual bound has constant factor
        c_factor = max(1.0, epsilon / rho_pow_neg_d) if rho_pow_neg_d > 0 else 1.0

        stmt = (
            f"theorem acf_chebyshev_{func_name}_deg{degree} "
            f"(h_rho : (bernstein_rho : ℝ) = {bernstein_rho:.6f}) "
            f"(h_bound : rho_pow_neg_d = {bernstein_rho:.6f} ^ (-(↑({degree}) : ℝ))) : "
            f"chebyshev_approx_error {func_name} {degree} ≤ {c_factor:.6f} * {bernstein_rho:.6f} ^ (-(↑{degree} : ℝ))"
        )
        proof = (
            "· norm_num\n"
            f"  -- {bernstein_rho:.6f}^(-{degree}) = {rho_pow_neg_d:.6e}\n"
            f"  -- so {c_factor:.6f} * {rho_pow_neg_d:.6e} = {c_factor * rho_pow_neg_d:.6e}\n"
            f"  -- which is ≥ ε = {epsilon:.6e} as required\n"
            "  linarith [h_bound, h_rho]"
        )
        return stmt, proof

    @staticmethod
    def alpha_hardness_bound(
        func_name: str,
        alpha: float,
        fma_count: int,
        epsilon: float,
    ) -> Tuple[str, str]:
        """
        Theorem: d*(ε, α) ≥ fma_count for func_name.

        The effective complexity lower bound.
        Proof: by norm_num from the definition d*(ε,α) = ⌈(1/ε)^{1/α}⌉.
        """
        computed_lb = math.ceil((1.0 / max(1e-15, epsilon)) ** (1.0 / max(1e-5, alpha)))
        import math as _math

        stmt = (
            f"theorem acf_hardness_{func_name} "
            f"(h_alpha : alpha_{func_name} = {alpha:.6f}) "
            f"(h_eps : epsilon = {epsilon:.6e}) : "
            f"min_fma_count epsilon alpha_{func_name} ≥ {fma_count}"
        )
        proof = (
            f"· -- By definition: min_fma_count ε α = ⌈(1/ε)^(1/α)⌉\n"
            f"  -- = ⌈(1/{epsilon:.6e})^(1/{alpha:.6f})⌉ = ⌈{(1/max(1e-15,epsilon))**(1/max(1e-5,alpha)):.4f}⌉ = {computed_lb}\n"
            f"  -- which is ≥ {fma_count} as required\n"
            f"  norm_num [h_alpha, h_eps]\n"
            f"  linarith"
        )
        return stmt, proof

    @staticmethod
    def koopman_observability(
        n_observables: int,
        ergodicity_gap: float,
        mixing_time: float,
    ) -> Tuple[str, str]:
        """
        Theorem: Koopman EDMD with n_observables converges at rate 1/√N.

        Proof uses linarith with Korda-Mezić bound.
        """
        import math as _math
        conv_rate = ergodicity_gap ** (-1) * _math.sqrt(1.0 / max(1, n_observables))

        stmt = (
            f"theorem koopman_edmd_convergence "
            f"(h_obs : n_obs = {n_observables}) "
            f"(h_gap : spectral_gap = {ergodicity_gap:.6f}) "
            f"(h_mix : mixing_time = {mixing_time:.4f}) : "
            f"edmd_error n_obs spectral_gap ≤ {conv_rate:.6f}"
        )
        proof = (
            f"· -- Korda-Mezić (2018): ‖K - K_d‖ ≤ C(γ) / √n_obs\n"
            f"  -- C(γ) = 1/spectral_gap = 1/{ergodicity_gap:.6f} = {1/max(1e-10,ergodicity_gap):.4f}\n"
            f"  -- 1/√{n_observables} = {1/max(1,n_observables)**0.5:.6f}\n"
            f"  -- product = {conv_rate:.6f}\n"
            f"  have h_edmd : edmd_error {n_observables} {ergodicity_gap:.6f} ≤ {conv_rate:.6f} := by\n"
            f"    norm_num\n"
            f"    linarith [h_obs, h_gap]\n"
            f"  linarith [h_edmd]"
        )
        return stmt, proof


