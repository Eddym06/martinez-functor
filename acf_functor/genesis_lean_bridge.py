class GenesisLeanBridge:
    """
    Closed-loop bridge: Genesis conjectures → Lean verification → Theorem catalog.

    Usage
    -----
    >>> bridge = GenesisLeanBridge(catalog_path="acf_theorem_catalog.json")
    >>> conj = bridge.conjecture_from_evidence({
    ...     "func": "sin",
    ...     "degree": 20,
    ...     "epsilon": 1e-8,
    ...     "bernstein_rho": 2.718,
    ... })
    >>> result = bridge.verify(conj)
    >>> bridge.update_catalog(result)
    """

    def __init__(
        self,
        catalog_path: str = "acf_theorem_catalog.json",
        lean_timeout_s: float = 20.0,
        reject_tautologies: bool = True,
    ):
        self.catalog_path = catalog_path
        self.reject_tautologies = reject_tautologies
        self.lean_tester = LeanFileTester(timeout_s=lean_timeout_s)
        self.template_lib = ACFLeanTemplateLibrary()
        self.catalog: List[CatalogEntry] = self._load_catalog()
        self._refuted_ids: set = set()

    def _load_catalog(self) -> List[CatalogEntry]:
        if os.path.isfile(self.catalog_path):
            try:
                with open(self.catalog_path, "r") as f:
                    data = json.load(f)
                return [CatalogEntry(**d) for d in data]
            except Exception:
                pass
        return []

    def _save_catalog(self) -> None:
        with open(self.catalog_path, "w") as f:
            import dataclasses
            json.dump(
                [dataclasses.asdict(e) for e in self.catalog],
                f,
                indent=2,
                default=str,
            )

    def conjecture_from_evidence(
        self, evidence: Dict[str, Any]
    ) -> ACFConjecture:
        """
        Generate a Lean conjecture from empirical ACF evidence.

        Evidence keys (at least one of the following sets):
          Chebyshev: {func, degree, epsilon, bernstein_rho}
          Hardness:  {func, alpha, fma_count, epsilon}
          Koopman:   {n_obs, ergodicity_gap, mixing_time}

        Returns an ACFConjecture with lean_statement + lean_proof generated
        by the template library.
        """
        if "bernstein_rho" in evidence and "degree" in evidence:
            func = evidence.get("func", "f")
            stmt, proof = ACFLeanTemplateLibrary.chebyshev_error_bound(
                func_name=func,
                degree=int(evidence["degree"]),
                epsilon=float(evidence.get("epsilon", 1e-6)),
                bernstein_rho=float(evidence["bernstein_rho"]),
            )
            origin = "chebyshev_error_bound"
            conj_id = f"cheb_{func}_d{evidence['degree']}"

        elif "alpha" in evidence and "fma_count" in evidence:
            func = evidence.get("func", "f")
            stmt, proof = ACFLeanTemplateLibrary.alpha_hardness_bound(
                func_name=func,
                alpha=float(evidence["alpha"]),
                fma_count=int(evidence["fma_count"]),
                epsilon=float(evidence.get("epsilon", 1e-6)),
            )
            origin = "alpha_hardness"
            conj_id = f"hardness_{func}_alpha{evidence['alpha']:.3f}"

        elif "n_obs" in evidence and "ergodicity_gap" in evidence:
            stmt, proof = ACFLeanTemplateLibrary.koopman_observability(
                n_observables=int(evidence["n_obs"]),
                ergodicity_gap=float(evidence["ergodicity_gap"]),
                mixing_time=float(evidence.get("mixing_time", 10.0)),
            )
            origin = "koopman_observability"
            conj_id = f"koopman_obs_{evidence['n_obs']}"

        else:
            raise ValueError(
                "Evidence must contain one of: {bernstein_rho+degree}, "
                "{alpha+fma_count}, or {n_obs+ergodicity_gap}."
            )

        return ACFConjecture(
            conjecture_id=conj_id,
            statement=stmt,
            lean_statement=stmt,
            lean_proof=proof,
            origin=origin,
            evidence=evidence,
        )

    def verify(self, conj: ACFConjecture) -> BridgeVerificationResult:
        """
        Verify an ACFConjecture through the Lean bridge.

        Steps:
        1. Reject tautologies.
        2. Run `lean --check` on the proof.
        3. Return status and Lean output.
        """
        t0 = time.time()

        # ── Tautology check (DEBILIDAD #2) ──────────────────────────────
        proof = conj.lean_proof or ""
        if self.reject_tautologies and is_tautological(proof):
            return BridgeVerificationResult(
                conjecture=conj,
                status=ConjectureStatus.TAUTOLOGICAL,
                lean_output="REJECTED: proof is tautological (restates hypothesis)",
                is_tautological=True,
                proof_used="(none — tautology)",
                time_s=time.time() - t0,
                error_msg="DEBILIDAD #2: tautological proof rejected by bridge",
            )

        # ── Build Lean file ──────────────────────────────────────────────
        lean_preamble = (
            "-- ACF Theorem: auto-generated by GenesisLeanBridge\n"
            "-- WARNING: uses axiom stubs; real proofs require Mathlib\n\n"
            "-- Axiom stubs for ACF definitions:\n"
            f"axiom chebyshev_approx_error : (ℝ → ℝ) → ℕ → ℝ\n"
            f"axiom min_fma_count : ℝ → ℝ → ℕ\n"
            f"axiom edmd_error : ℕ → ℝ → ℝ\n"
            f"axiom bernstein_rho : ℝ\n"
        )
        lean_code = lean_preamble + "\n" + conj.lean_statement + " := by\n" + proof + "\n"

        # ── Check with Lean ──────────────────────────────────────────────
        success, lean_out = self.lean_tester.check_proof(lean_code)

        # Determine decisive proof tactic
        tactic_used = "(unknown)"
        for tactic in ["linarith", "norm_num", "apply", "ring", "calc", "have"]:
            if tactic in proof:
                tactic_used = tactic
                break

        if lean_out == "LEAN_NOT_FOUND":
            # Can't run Lean; mark as PLAUSIBLE based on tautology check only
            status = ConjectureStatus.PLAUSIBLE
        elif lean_out == "TIMEOUT":
            status = ConjectureStatus.TIMEOUT
        elif success:
            status = ConjectureStatus.PROVED
        else:
            # Check if counter-example language
            if "false" in lean_out.lower() or "counter" in lean_out.lower():
                status = ConjectureStatus.REFUTED
                self._refuted_ids.add(conj.conjecture_id)
            else:
                status = ConjectureStatus.PLAUSIBLE  # proof failed but not refuted

        return BridgeVerificationResult(
            conjecture=conj,
            status=status,
            lean_output=lean_out[:2000],
            is_tautological=False,
            proof_used=tactic_used,
            time_s=time.time() - t0,
        )

    def update_catalog(self, result: BridgeVerificationResult) -> bool:
        """
        Add a PROVED (or PLAUSIBLE) result to the theorem catalog.

        Returns True if added, False if already present or refuted/tautological.
        """
        if result.status in (ConjectureStatus.TAUTOLOGICAL, ConjectureStatus.REFUTED, ConjectureStatus.ERROR):
            return False

        conj = result.conjecture
        # Check for duplicates
        existing_ids = {e.theorem_id for e in self.catalog}
        if conj.conjecture_id in existing_ids:
            return False

        entry = CatalogEntry(
            theorem_id=conj.conjecture_id,
            statement=conj.statement,
            lean_statement=conj.lean_statement,
            lean_proof=conj.lean_proof or "",
            status=result.status,
            origin=conj.origin,
        )
        self.catalog.append(entry)
        self._save_catalog()
        return True

    def run_evidence_batch(
        self, evidence_list: List[Dict[str, Any]]
    ) -> List[BridgeVerificationResult]:
        """
        Process a batch of evidence items: conjecture → verify → catalog.
        Returns all verification results.
        """
        results: List[BridgeVerificationResult] = []
        for evid in evidence_list:
            try:
                conj = self.conjecture_from_evidence(evid)
                if conj.conjecture_id in self._refuted_ids:
                    continue
                result = self.verify(conj)
                self.update_catalog(result)
                results.append(result)
            except Exception as e:
                pass  # log silently
        return results

    def catalog_summary(self) -> str:
        proved   = sum(1 for e in self.catalog if e.status == ConjectureStatus.PROVED)
        plaus    = sum(1 for e in self.catalog if e.status == ConjectureStatus.PLAUSIBLE)
        total    = len(self.catalog)
        refuted  = len(self._refuted_ids)
        return (
            f"ACF Theorem Catalog: {total} entries "
            f"({proved} proved, {plaus} plausible, {refuted} refuted)"
        )


