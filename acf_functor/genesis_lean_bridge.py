class LeanFileTester:
    """
    Builds a temporary Lean 4 file and checks it with the local Lean binary.
    """

    def __init__(self, lean_binary: Optional[str] = None, timeout_s: float = 30.0):
        self.timeout_s = timeout_s
        if lean_binary:
            self.lean_bin = lean_binary
        else:
            # Try to find lean in the project's local installation
            candidates = [
                "/home/Martínez's Invariant/lean-4.29.0-rc6-linux/bin/lean",
                "/home/Martínez's Invariant/lean-4.28.0-linux/bin/lean",
                "/usr/bin/lean",
                "/usr/local/bin/lean",
            ]
            self.lean_bin = next(
                (c for c in candidates if os.path.isfile(c)), "lean"
            )

    def check_proof(self, lean_code: str) -> Tuple[bool, str]:
        """
        Write lean_code to a temp file and check it.

        Returns (success: bool, output: str).
        """
        with tempfile.NamedTemporaryFile(
            suffix=".lean", mode="w", delete=False, encoding="utf-8"
        ) as f:
            f.write(lean_code)
            fname = f.name

        try:
            result = subprocess.run(
                [self.lean_bin, fname],
                capture_output=True,
                text=True,
                timeout=self.timeout_s,
            )
            success = (
                result.returncode == 0
                and "error" not in result.stderr.lower()
                and "sorry" not in result.stdout.lower()
            )
            output = result.stdout + result.stderr
            return success, output
        except subprocess.TimeoutExpired:
            return False, "TIMEOUT"
        except FileNotFoundError:
            return False, "LEAN_NOT_FOUND"
        finally:
            try:
                os.unlink(fname)
            except OSError:
                pass


