"""
Poema WASM Backend — WebAssembly Text Format (WAT) code generator.

Transpiles FMA chains to:
  - WAT (WebAssembly Text Format) — readable, inspectable source
  - WASM binary (if wat2wasm is available)
  - JavaScript ES module loader with optional Node.js + browser targets
  - Structured control flow matching the FMA evaluation loop

Architecture:
  WasmBackend(BackendProtocol)
    .compile(fma_seq, ast, domain, precision) -> BackendResult
    .emit_wat(fma_seq, precision, module_name) -> str
    .emit_js_loader(wasm_path, module_name) -> str
    .assemble(wat_source, out_path) -> Optional[str]  # calls wat2wasm if available
    .verify_available() -> bool

Precision mapping:
  fp64 → f64 (IEEE 754 double)
  fp32 → f32 (IEEE 754 single)
  complex128 → two f64 channels (real + imag)

WebAssembly FMA:
  WASM has no native FMA instruction in MVP. We emit:
    local.get $acc
    f64.mul  ;; or f32.mul
    local.get $bias
    f64.add  ;; or f32.add
  Modern engines (V8, SpiderMonkey) may fuse mul+add to HW FMA.
"""

from __future__ import annotations

import os
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, List, Optional, Tuple

from .protocol import BackendCapabilities, BackendProtocol, BackendResult

# ─────────────────────────────────────────────────────────────────────────────
# WAT code generation helpers
# ─────────────────────────────────────────────────────────────────────────────

_WAT_HEADER = """;; ================================================================
;; Poema FMA chain evaluator — WebAssembly Text Format (WAT)
;; Generated by poema.backends.wasm_backend
;; Module  : {module_name}
;; Depth   : {n_stages} FMA stages
;; Precision: {precision}
;; ================================================================
(module
"""

_WAT_CONST_SECTION = """;; --- Constant data: FMA weights and biases ---
;; Stored as f64 literals inlined into func body (constant folding by engine)
"""

_WAT_EVAL_FP64 = """;; poema_eval_fp64: (param f64 x) (result f64 y)
  (func (export "poema_eval_fp64") (param $x f64) (result f64)
    (local $acc f64)
    (local.set $acc (local.get $x))
{fma_body}
    (local.get $acc)
  )
"""

_WAT_EVAL_FP32 = """;; poema_eval_fp32: (param f32 x) (result f32 y)
  (func (export "poema_eval_fp32") (param $x f32) (result f32)
    (local $acc f32)
    (local.set $acc (local.get $x))
{fma_body}
    (local.get $acc)
  )
"""

_WAT_EVAL_COMPLEX = """;; poema_eval_complex: (param f64 xr xi) (result f64 yr yi)
;; Complex FMA: (wr+i*wi)*(ar+i*ai) + (br+i*bi)
  (func (export "poema_eval_complex") (param $xr f64) (param $xi f64)
        (result f64 f64)
    (local $ar f64)
    (local $ai f64)
    (local $tr f64)
    (local $ti f64)
    (local.set $ar (local.get $xr))
    (local.set $ai (local.get $xi))
{cmplx_body}
    (local.get $ar)
    (local.get $ai)
  )
"""

_WAT_BATCH_EVAL_FP64 = """;; poema_eval_batch_fp64: evaluate n elements from linear memory
;; Memory layout: input at offset 0, output at offset n*8
  (func (export "poema_eval_batch_fp64") (param $n i32)
    (local $i i32)
    (local $acc f64)
    (local.set $i (i32.const 0))
    (block $break
      (loop $loop
        (br_if $break (i32.ge_u (local.get $i) (local.get $n)))
        ;; load x[i] from memory at offset i*8
        (local.set $acc
          (f64.load (i32.mul (local.get $i) (i32.const 8))))
{batch_fma_body}
        ;; store y[i] at offset (n + i) * 8
        (f64.store
          (i32.mul (i32.add (local.get $n) (local.get $i)) (i32.const 8))
          (local.get $acc))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $loop)
      )
    )
  )
"""

_WAT_HORNER_FP64 = """;; poema_horner_fp64: Horner polynomial eval for degree (n_coeffs-1)
;; Memory: coefficients at offset 0 (f64 each), evaluate at x param
  (func (export "poema_horner_fp64")
        (param $x f64) (param $n_coeffs i32) (result f64)
    (local $acc f64)
    (local $k i32)
    (local.set $k (i32.sub (local.get $n_coeffs) (i32.const 1)))
    ;; acc = coeffs[n_coeffs - 1]
    (local.set $acc
      (f64.load (i32.mul (local.get $k) (i32.const 8))))
    (block $break
      (loop $loop
        (local.set $k (i32.sub (local.get $k) (i32.const 1)))
        (br_if $break (i32.lt_s (local.get $k) (i32.const 0)))
        ;; acc = acc * x + coeffs[k]
        (local.set $acc
          (f64.add
            (f64.mul (local.get $acc) (local.get $x))
            (f64.load (i32.mul (local.get $k) (i32.const 8)))))
        (br $loop)
      )
    )
    (local.get $acc)
  )
"""

_WAT_MEMORY = """;; Shared linear memory: 1 page = 64 KB (≥ 4096 f64 = 32 KB)
  (memory (export "memory") 2)
"""

_WAT_FOOTER = """)
;; end of module
"""

_JS_LOADER_TEMPLATE = """\
// Poema WASM Loader — auto-generated by poema.backends.wasm_backend
// Module: {module_name}  |  FMA depth: {n_stages}  |  Precision: {precision}
// Usage (Node.js / browser):
//   const {{ evalFMA, evalBatch }} = await loadPoema('{wasm_filename}');

export async function loadPoema(wasmPath = '{wasm_filename}') {{
  const source = typeof fetch !== 'undefined'
    ? await WebAssembly.instantiateStreaming(fetch(wasmPath))
    : WebAssembly.instantiate(require('fs').readFileSync(wasmPath));
  const {{ instance }} = await source;
  const exports = instance.exports;
  const mem = new Float64Array(exports.memory.buffer);

  /**
   * Evaluate the FMA chain on a single scalar.
   * @param {{number}} x — input value
   * @returns {{number}} evaluated FMA(x)
   */
  function evalFMA(x) {{
    return exports.poema_eval_fp64(x);
  }}

  /**
   * Evaluate the FMA chain on an array of n values.
   * Results written to the second half of WASM memory.
   * @param {{Float64Array}} xs — input array
   * @returns {{Float64Array}} evaluated outputs
   */
  function evalBatch(xs) {{
    const n = xs.length;
    mem.set(xs, 0);                    // copy input to WASM memory offset 0
    exports.poema_eval_batch_fp64(n);  // evaluate in-place
    return mem.slice(n, 2 * n);        // output is at offset n*8
  }}

  return {{ evalFMA, evalBatch, exports, memory: exports.memory }};
}}
"""


# ─────────────────────────────────────────────────────────────────────────────
# Backend class
