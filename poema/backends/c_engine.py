    # ── Code generation ──────────────────────────────────────────────────────

    def _emit_c_source(
        self,
        fma_sequence: List[Any],
        precision: str,
        is_complex: bool = False,
    ) -> str:
        n = len(fma_sequence)
        if n == 0:
            # trivial identity
            fma_sequence = [type("FMA", (), {"weight": 1.0, "bias": 0.0})()]
            n = 1

        if self._force_avx:
            use_avx = self._force_avx in ("avx2", "avx512")
            use_avx512 = self._force_avx == "avx512"
        else:
            use_avx   = self._caps.has_avx2 or self._caps.has_avx512
            use_avx512 = self._caps.has_avx512

        use_openmp = self._caps.has_openmp and self._use_openmp
        ctype = "double" if precision in ("fp64", "double") else "float"

        avx_include  = "#include <immintrin.h>" if use_avx else ""
        omp_include  = "#include <omp.h>" if use_openmp else ""

        # header
        src = _C_HEADER.format(
            precision=precision, n_stages=n,
            use_avx=str(use_avx), use_openmp=str(use_openmp),
            avx_include=avx_include, omp_include=omp_include,
        )

        if is_complex:
            # complex weights
            wr = [float(getattr(i.weight, 'real', float(i.weight))) for i in fma_sequence]
            wi = [float(getattr(i.weight, 'imag', 0.0)) for i in fma_sequence]
            br = [float(getattr(i.bias, 'real', float(i.bias))) for i in fma_sequence]
            bi = [float(getattr(i.bias, 'imag', 0.0)) for i in fma_sequence]
            src += _C_COMPLEX_BODY.format(
                wr_list=", ".join(f"{v:.17g}" for v in wr),
                wi_list=", ".join(f"{v:.17g}" for v in wi),
                br_list=", ".join(f"{v:.17g}" for v in br),
                bi_list=", ".join(f"{v:.17g}" for v in bi),
            )
            src += _C_FOOTER
            return src

        # real weights
        def _float_c(v: Any) -> float:
            try:
                return float(v)
            except Exception:
                return 0.0

        ws = [_float_c(i.weight) for i in fma_sequence]
        bs = [_float_c(i.bias)   for i in fma_sequence]

        w_fmt = ", ".join(f"{v:.17g}" for v in ws)
        b_fmt = ", ".join(f"{v:.17g}" for v in bs)

        src += _C_WEIGHTS_DECL.format(
            ctype=ctype,
            weight_list=w_fmt,
            bias_list=b_fmt,
        )

        # SIMD paths
        if use_avx512 and precision in ("fp64", "double"):
            src += _C_AVX512_FP64
            src += _C_AVX2_FP64   # also emit avx2 for the 4-tail
        elif use_avx and precision in ("fp64", "double"):
            src += _C_AVX2_FP64
        elif use_avx and precision in ("fp32", "float"):
            src += _C_AVX2_FP32

        src += _C_SCALAR_FALLBACK.format(suffix=precision, ctype=ctype)
        src += _C_OPENMP_BATCH.format(suffix=precision, ctype=ctype)

        # ——— Level-2: ILP-optimal dual/quad accumulators ——————————————————
        if use_avx and precision in ("fp64", "double"):
            src += _C_DUAL_ACCUM_AVX2_FP64
        if use_avx512 and precision in ("fp64", "double"):
            src += _C_QUAD_ACCUM_AVX512_FP64

        # Best kernel name for cache-blocked dispatch & gradient
        if use_avx512 and precision in ("fp64", "double"):
            best_kernel = "_poema_avx512_fp64_quad"
        elif use_avx and precision in ("fp64", "double"):
            best_kernel = "_poema_avx2_fp64_dual"
        elif use_avx and precision in ("fp32", "float"):
            best_kernel = "_poema_avx2_fp32"
        else:
            best_kernel = f"_poema_scalar_{precision}"

        # Cache-blocked L1-tile dispatch
        src += _C_CACHE_BLOCKED_TPL.format(
            suffix=precision, ctype=ctype, best_kernel=best_kernel)
        # Batched matrix evaluation + reduce
        src += _C_MATRIX_EVAL_TPL.format(suffix=precision, ctype=ctype)
        # Horner polynomial + forward-mode AD  (FP64 only)
        if precision in ("fp64", "double"):
            src += _C_HORNER_TPL
            src += _C_GRADIENT_TPL.format(best_kernel=best_kernel)

        # Public dispatch routes through cache-blocked path
        if precision in ("fp64", "double"):
            fp64_body = "    poema_eval_fp64_blocked(x, y, n);"
            fp32_body = "    (void)x; (void)y; (void)n;"
        else:
            fp64_body = "    (void)x; (void)y; (void)n;"
            fp32_body = "    poema_eval_fp32_blocked(x, y, n);"

        src += _C_PUBLIC_DISPATCH.format(fp64_dispatch=fp64_body, fp32_dispatch=fp32_body)
        src += _C_FOOTER
        return src

    # ── Compilation ──────────────────────────────────────────────────────────

    def _compile_source(
        self,
        c_source: str,
        lib_name: str,
        precision: str,
        is_complex: bool = False,
    ) -> Tuple[Optional[Any], str]:
        """
        Write C source to disk, compile to shared library, load via cffi.
        Returns (cffi_lib, lib_path).
        """
        src_path = self._build_dir / f"{lib_name}.c"
        lib_path = self._build_dir / f"{lib_name}.so"

        with open(src_path, "w") as f:
            f.write(c_source)

        cflags = ["-O3", "-march=native", "-ffast-math", "-funroll-loops",
                  "-fPIC", "-shared", "-std=c11"]
        if self._caps.has_openmp and self._use_openmp:
            cflags.append("-fopenmp")
        cflags += self._extra_cflags

        cmd = [self._compiler] + cflags + [str(src_path), "-o", str(lib_path), "-lm"]
        if self._verbose:
            print(f"[CEngine] Compiling: {' '.join(cmd)}")

        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            raise RuntimeError(
                f"C compilation failed (rc={r.returncode}):\n"
                f"STDOUT: {r.stdout}\nSTDERR: {r.stderr}"
            )

        # Load via cffi
        try:
            from cffi import FFI
            ffi = FFI()
            if is_complex:
                ffi.cdef("""
                    void poema_eval_complex128(
                        const double *xr, const double *xi,
                        double *yr, double *yi, uint64_t n);
                """)
            else:
                ffi.cdef("""
                    void poema_eval_fp64(const double *x, double *y, uint64_t n);
                    void poema_eval_fp32(const float  *x, float  *y, uint64_t n);
                    void poema_eval_fp64_omp(const double *X, double *Y, uint64_t batch);
                    void poema_eval_fp32_omp(const float  *X, float  *Y, uint64_t batch);
                    void poema_eval_fp64_blocked(const double *x, double *y, uint64_t n);
                    void poema_eval_fp32_blocked(const float  *x, float  *y, uint64_t n);
                    void poema_matrix_eval_fp64(const double *X, double *Y,
                                               uint64_t rows, uint64_t cols);
                    void poema_matrix_eval_fp32(const float  *X, float  *Y,
                                               uint64_t rows, uint64_t cols);
                    double poema_reduce_sum_fp64(const double *x, uint64_t n);
                    double poema_reduce_sum_fp32(const float  *x, uint64_t n);
                    void poema_horner_fp64(const double *coeffs, uint64_t n_coeffs,
                                          const double *x, double *y, uint64_t n_x);
                    void poema_grad_fp64(const double *x, double *y, double *dydx,
                                        uint64_t n);
                    double poema_bench_fp64(const double *x, double *y,
                                            uint64_t n, uint64_t reps);
                    double poema_bench_grad_fp64(const double *x, double *y,
                                                 double *dydx, uint64_t n, uint64_t reps);
                """)
            lib = ffi.dlopen(str(lib_path))
            return lib, ffi, str(lib_path)
        except ImportError:
            return None, None, str(lib_path)

    # ── Callable construction ────────────────────────────────────────────────

    def _make_callable(
        self,
        lib: Any,
        ffi: Any,
        precision: str,
        is_complex: bool = False,
    ) -> Callable:
        if lib is None or ffi is None:
            return None

        if is_complex:
            def _call_complex(z: np.ndarray) -> np.ndarray:
                z   = np.asarray(z, dtype=np.complex128)
                xr  = np.ascontiguousarray(z.real, dtype=np.float64)
                xi  = np.ascontiguousarray(z.imag, dtype=np.float64)
                yr  = np.empty_like(xr)
                yi  = np.empty_like(xi)
                n   = len(xr)
                lib.poema_eval_complex128(
                    ffi.cast("double *", xr.ctypes.data),
                    ffi.cast("double *", xi.ctypes.data),
                    ffi.cast("double *", yr.ctypes.data),
                    ffi.cast("double *", yi.ctypes.data),
                    n,
                )
                return yr + 1j * yi
            return _call_complex

        if precision in ("fp64", "double"):
            def _call_fp64(x: np.ndarray) -> np.ndarray:
                x = np.ascontiguousarray(x, dtype=np.float64)
                y = np.empty_like(x)
                lib.poema_eval_fp64(
                    ffi.cast("double *", x.ctypes.data),
                    ffi.cast("double *", y.ctypes.data),
                    len(x),
                )
                return y
            return _call_fp64
        else:
            def _call_fp32(x: np.ndarray) -> np.ndarray:
                x = np.ascontiguousarray(x, dtype=np.float32)
                y = np.empty_like(x)
                lib.poema_eval_fp32(
                    ffi.cast("float *", x.ctypes.data),
                    ffi.cast("float *", y.ctypes.data),
                    len(x),
                )
                return y
            return _call_fp32

    # ── BackendProtocol interface ────────────────────────────────────────────

    def compile(
        self,
        fma_sequence: List[Any],
        source_ast: Any,
        domain: Tuple[float, float] = (-1.0, 1.0),
        precision: str = "fp64",
        module_name: Optional[str] = None,
        **kwargs,
    ) -> BackendResult:
        is_complex = kwargs.get("complex_mode", False)
        n = len(fma_sequence)

        # Stable hash for caching compiled libs
        w_hash = hashlib.md5(
            str([(getattr(i.weight, '__float__', lambda: i.weight)(),
                  getattr(i.bias,   '__float__', lambda: i.bias)())
                 for i in fma_sequence]).encode()
        ).hexdigest()[:12]
        lib_name = f"poema_fma_{precision}_{n}_{w_hash}"

        c_source = self._emit_c_source(fma_sequence, precision, is_complex=is_complex)
        lib, ffi, lib_path = self._compile_source(c_source, lib_name, precision, is_complex)

        fn = self._make_callable(lib, ffi, precision, is_complex)

        # Fallback: pure Python FMA if compile failed
        if fn is None:
            ws = [float(getattr(i.weight, 'real', i.weight)) for i in fma_sequence]
            bs = [float(getattr(i.bias,   'real', i.bias))   for i in fma_sequence]
            def _fallback(x):
                y = np.asarray(x, dtype=np.float64).copy()
                for w, b in zip(ws, bs):
                    y = w * y + b
                return y
            fn = _fallback

        return BackendResult(
            callable_fn=fn,
            emitted_code=c_source,
            emitted_path=lib_path,
            fma_count=n,
            backend_name="c_native",
            extra={
                "lib_path"  : lib_path,
                "_lib"      : lib,       # cffi lib object — used by advanced methods
                "_ffi"      : ffi,       # cffi FFI object
                "compiler"  : self._compiler,
                "has_avx2"  : self._caps.has_avx2,
                "has_avx512": self._caps.has_avx512,
                "has_openmp": self._caps.has_openmp,
                "simd_level": "avx512" if self._caps.has_avx512 else
                              "avx2"   if self._caps.has_avx2   else "scalar",
            },
        )

    # ── Benchmarking ─────────────────────────────────────────────────────────

    def benchmark(
        self,
        fma_sequence: List[Any],
        n_elements: int = 1_000_000,
        reps: int = 20,
        warmup: int = 3,
        precision: str = "fp64",
    ) -> CEngineBenchmark:
        """
        Run timing benchmark comparing C engine vs NumPy baseline.
        Returns CEngineBenchmark with ns/call, GB/s, GFLOPS, and speedup.
        """
        result = self.compile(fma_sequence, None, precision=precision)
        fn_c = result.callable_fn
        n_stages = len(fma_sequence)

        dtype = np.float64 if precision in ("fp64", "double") else np.float32
        rng  = np.random.default_rng(0)
        x    = rng.standard_normal(n_elements).astype(dtype)
        y    = np.empty_like(x)

        # Warm-up
        for _ in range(warmup):
            fn_c(x)

        # C engine timing
        t0 = time.perf_counter_ns()
        for _ in range(reps):
            fn_c(x)
        t1 = time.perf_counter_ns()
        ns_c = (t1 - t0) / reps

        # NumPy baseline
        ws = [float(getattr(i.weight, 'real', i.weight)) for i in fma_sequence]
        bs = [float(getattr(i.bias, 'real', i.bias)) for i in fma_sequence]
        def numpy_eval(x):
            y = x.copy()
            for w, b in zip(ws, bs):
                y = w * y + b
            return y

        for _ in range(warmup):
            numpy_eval(x)

        t0 = time.perf_counter_ns()
        for _ in range(reps):
            numpy_eval(x)
        t1 = time.perf_counter_ns()
        ns_np = (t1 - t0) / reps

        # Metrics
        bytes_per_elem = 8 if precision in ("fp64", "double") else 4
        gb_s  = (n_elements * bytes_per_elem * 2) / (ns_c * 1e-9) / 1e9
        # 2 FLOPs per FMA step (multiply + add), n_stages steps, n_elements elems
        gflops = (2 * n_stages * n_elements) / (ns_c * 1e-9) / 1e9
        speedup = ns_np / ns_c if ns_c > 0 else 0.0

        return CEngineBenchmark(
            n_elements=n_elements,
            n_stages=n_stages,
            precision=precision,
            ns_per_call=ns_c,
            gb_per_sec=gb_s,
            gflops=gflops,
            speedup_vs_numpy=speedup,
        )

