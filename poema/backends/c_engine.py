@dataclass
class CEngineCapabilities:
    compiler: str = ""
    has_avx2: bool = False
    has_avx512: bool = False
    has_openmp: bool = False
    has_cffi: bool = False

    def summary(self) -> str:
        avx = "AVX-512" if self.has_avx512 else ("AVX2" if self.has_avx2 else "scalar")
        omp = "OpenMP" if self.has_openmp else "single-thread"
        return f"C Engine: {self.compiler} | {avx} | {omp} | cffi={self.has_cffi}"


@dataclass
class CEngineBenchmark:
    n_elements: int = 0
    n_stages: int = 0
    precision: str = ""
    ns_per_call: float = 0.0
    gb_per_sec: float = 0.0
    gflops: float = 0.0
    speedup_vs_numpy: float = 0.0

    def report(self) -> str:
        return (
            f"CEngine Bench [{self.precision}, n={self.n_elements}, depth={self.n_stages}]\n"
            f"  {self.ns_per_call:.1f} ns/call  |  {self.gb_per_sec:.2f} GB/s  |  "
            f"{self.gflops:.2f} GFLOPS  |  {self.speedup_vs_numpy:.1f}× vs NumPy"
        )


class CNativeEngine(BackendProtocol):
    """
    The Poema Native C Engine.

    FMA chains are transpiled to ANSI C with SIMD / OpenMP optimizations,
    compiled with gcc/clang -O3, and loaded via cffi for zero-overhead calls.

    Performance characteristics:
      FP64 AVX2:    ~4 doubles/clock × 4 GHz = ~16 GFLOPS/core
      FP64 AVX-512: ~8 doubles/clock × 4 GHz = ~32 GFLOPS/core
      FP32 AVX2:    ~16 GFLOPS/core (8 floats × 2 FMA ops)
      OpenMP 4T:    ~4× additional

    Usage:
        from poema.backends.c_engine import CNativeEngine
        engine = CNativeEngine()
        result = engine.compile(fma_seq, ast, precision="fp64")
        y = result.callable_fn(x)
        bench = engine.benchmark(fma_seq, n_elements=1_000_000)
        print(bench.report())
    """

    _BUILD_DIR = Path(tempfile.gettempdir()) / "poema_c_engine"

    def __init__(
        self,
        compiler: Optional[str] = None,
        use_openmp: bool = True,
        force_avx: Optional[str] = None,   # "avx2", "avx512", "scalar", None=auto
        extra_cflags: Optional[List[str]] = None,
        build_dir: Optional[str] = None,
        verbose: bool = False,
    ):
        self._compiler = compiler or self._find_compiler()
        self._use_openmp = use_openmp
        self._force_avx = force_avx
        self._extra_cflags = extra_cflags or []
        self._build_dir = Path(build_dir) if build_dir else self._BUILD_DIR
        self._build_dir.mkdir(parents=True, exist_ok=True)
        self._verbose = verbose
        self._caps = self._detect_capabilities()

    # ── Capability detection ─────────────────────────────────────────────────

    @staticmethod
    def _find_compiler() -> str:
        for cc in ("gcc", "clang", "cc"):
            try:
                subprocess.run([cc, "--version"], capture_output=True, check=True)
                return cc
            except (FileNotFoundError, subprocess.CalledProcessError):
                continue
        return "gcc"  # best-effort fallback

    def _detect_capabilities(self) -> CEngineCapabilities:
        caps = CEngineCapabilities(compiler=self._compiler)
        try:
            import cffi  # noqa: F401
            caps.has_cffi = True
        except ImportError:
            pass

        # CPU flags from /proc/cpuinfo on Linux
        if platform.system() == "Linux":
            try:
                with open("/proc/cpuinfo") as f:
                    flags = f.read()
                caps.has_avx2   = "avx2"   in flags
                caps.has_avx512 = "avx512f" in flags
            except Exception:
                pass
        elif platform.system() == "Darwin":
            r = subprocess.run(["sysctl", "-n", "machdep.cpu.features"],
                               capture_output=True, text=True)
            fl = r.stdout.upper()
