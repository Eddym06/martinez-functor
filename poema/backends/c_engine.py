    # ── High-level convenience API ────────────────────────────────────────────

    def evaluate(
        self,
        fma_sequence: List[Any],
        x: "np.ndarray",
        precision: str = "fp64",
        **kwargs,
    ) -> "np.ndarray":
        """One-shot: compile FMA chain and evaluate on x. Compiled lib is cached."""
        result = self.compile(fma_sequence, None, precision=precision, **kwargs)
        return result.callable_fn(np.asarray(x))

    def fuse_and_compile(
        self,
        chains: List[List[Any]],
        source_ast: Any = None,
        precision: str = "fp64",
        **kwargs,
    ) -> BackendResult:
        """Fuse multiple FMA chains by concatenation, then compile as one unit."""
        fused = [instr for chain in chains for instr in chain]
        return self.compile(fused, source_ast, precision=precision, **kwargs)

    def _get_lib_ffi(
        self,
        fma_sequence: Optional[List[Any]],
        precision: str,
        existing_result: Optional[BackendResult] = None,
    ) -> Tuple[Any, Any, BackendResult]:
        """Internal: obtain (lib, ffi, result) for advanced kernel calls."""
        if existing_result is not None:
            lib = existing_result.extra.get("_lib")
            ffi = existing_result.extra.get("_ffi")
            if lib is not None and ffi is not None:
                return lib, ffi, existing_result
        # compile a minimal chain to get the shared lib
        if fma_sequence:
            result = self.compile(fma_sequence, None, precision=precision)
        else:
            dummy = type("FMA", (), {"weight": 1.0, "bias": 0.0})
            result = self.compile([dummy()], None, precision=precision)
        return result.extra.get("_lib"), result.extra.get("_ffi"), result

    def evaluate_polynomial(
        self,
        coeffs: "np.ndarray",
        x_vals: "np.ndarray",
        precision: str = "fp64",
    ) -> "np.ndarray":
        """
        Evaluate polynomial via Horner's method using the native C Horner kernel.

        coeffs = [c0, c1, ..., cd]  where  p(x) = c0 + c1*x + ... + cd*x^d
        """
        cache_key = ("_horner", precision)
        if not hasattr(self, "_kernel_cache"):
            self._kernel_cache: Dict[Any, BackendResult] = {}
        if cache_key not in self._kernel_cache:
            dummy = type("FMA", (), {"weight": 1.0, "bias": 0.0})
            self._kernel_cache[cache_key] = self.compile([dummy()], None, precision=precision)
        r = self._kernel_cache[cache_key]
        lib = r.extra.get("_lib")
        ffi = r.extra.get("_ffi")
        if lib is None or ffi is None:
            return np.polynomial.polynomial.polyval(x_vals, coeffs)
        c_c = np.ascontiguousarray(coeffs, dtype=np.float64)
        x_c = np.ascontiguousarray(x_vals, dtype=np.float64)
        y_c = np.empty_like(x_c)
        lib.poema_horner_fp64(
            ffi.cast("double *", c_c.ctypes.data),
            len(c_c),
            ffi.cast("double *", x_c.ctypes.data),
            ffi.cast("double *", y_c.ctypes.data),
            len(x_c),
        )
        return y_c

    def evaluate_with_gradient(
        self,
        fma_sequence: List[Any],
        x: "np.ndarray",
        precision: str = "fp64",
    ) -> Tuple["np.ndarray", "np.ndarray"]:
        """
        Evaluate FMA chain AND compute dy/dx in one pass.
        For a linear FMA chain dy/dx = ∏ weights (constant over all x).
        Returns (y, dydx).
        """
        result = self.compile(fma_sequence, None, precision=precision)
        lib = result.extra.get("_lib")
        ffi = result.extra.get("_ffi")
        if lib is None or ffi is None:
            y = result.callable_fn(x)
            w_prod = 1.0
            for instr in fma_sequence:
                w_prod *= float(getattr(instr.weight, "real", instr.weight))
            return y, np.full_like(np.asarray(y, dtype=np.float64), w_prod)
        x_c    = np.ascontiguousarray(x, dtype=np.float64)
        y_c    = np.empty_like(x_c)
        dydx_c = np.empty_like(x_c)
        lib.poema_grad_fp64(
            ffi.cast("double *", x_c.ctypes.data),
            ffi.cast("double *", y_c.ctypes.data),
            ffi.cast("double *", dydx_c.ctypes.data),
            len(x_c),
        )
        return y_c, dydx_c

    def matrix_eval(
        self,
        fma_sequence: List[Any],
        X: "np.ndarray",
        precision: str = "fp64",
    ) -> "np.ndarray":
        """
        Evaluate FMA chain on 2-D input X[rows, cols].
        OpenMP-parallel across rows; cache-blocked SIMD within each row.
        """
        result = self.compile(fma_sequence, None, precision=precision)
        X_2d = np.atleast_2d(np.asarray(X))
        rows, cols = X_2d.shape
        lib = result.extra.get("_lib")
        ffi = result.extra.get("_ffi")
        if lib is None or ffi is None:
            return np.stack([result.callable_fn(X_2d[r]) for r in range(rows)])
        dtype = np.float64 if precision in ("fp64", "double") else np.float32
        X_c = np.ascontiguousarray(X_2d, dtype=dtype)
        Y_c = np.empty_like(X_c)
        if dtype == np.float64:
            lib.poema_matrix_eval_fp64(
                ffi.cast("double *", X_c.ctypes.data),
                ffi.cast("double *", Y_c.ctypes.data),
                rows, cols,
            )
        else:
            lib.poema_matrix_eval_fp32(
                ffi.cast("float *", X_c.ctypes.data),
                ffi.cast("float *", Y_c.ctypes.data),
                rows, cols,
            )
        return Y_c

    def reduce_sum(
        self,
        fma_sequence: List[Any],
        x: "np.ndarray",
        precision: str = "fp64",
    ) -> float:
        """Evaluate FMA chain on x and return the sum of all outputs."""
        result = self.compile(fma_sequence, None, precision=precision)
        lib = result.extra.get("_lib")
        ffi = result.extra.get("_ffi")
        if lib is None or ffi is None:
            return float(result.callable_fn(x).sum())
        dtype = np.float64 if precision in ("fp64", "double") else np.float32
        x_c = np.ascontiguousarray(x, dtype=dtype)
        if dtype == np.float64:
            return lib.poema_reduce_sum_fp64(
                ffi.cast("double *", x_c.ctypes.data), len(x_c))
        return lib.poema_reduce_sum_fp32(
            ffi.cast("float *", x_c.ctypes.data), len(x_c))

    def benchmark_full_suite(
        self,
        fma_sequence: List[Any],
        sizes: Optional[List[int]] = None,
        reps: int = 30,
        precision: str = "fp64",
    ) -> List["CEngineBenchmark"]:
        """
        Comprehensive benchmark across multiple array sizes.
        Covers L1 (4 K), L2 (64 K), L3 (4 M), DRAM (32 M) regimes.
        """
        if sizes is None:
            sizes = [4_096, 65_536, 524_288, 4_194_304, 33_554_432]
        results = []
        for n in sizes:
            try:
                b = self.benchmark(
                    fma_sequence, n_elements=n, reps=reps, precision=precision)
                results.append(b)
            except Exception:
                results.append(CEngineBenchmark(
                    n_elements=n, n_stages=len(fma_sequence), precision=precision,
                    ns_per_call=float("nan"), gb_per_sec=0.0,
                    gflops=0.0, speedup_vs_numpy=0.0,
                ))
        return results

    def print_benchmark_suite(
        self,
        fma_sequence: List[Any],
        sizes: Optional[List[int]] = None,
        reps: int = 30,
        precision: str = "fp64",
    ) -> str:
        """Run benchmark suite and return formatted multi-size report string."""
        results = self.benchmark_full_suite(fma_sequence, sizes, reps, precision)
        lines = [
            "=" * 76,
            f"  Poema CNativeEngine Benchmark Suite [{self._caps.summary()}]",
            f"  FMA stages: {len(fma_sequence)}  |  Precision: {precision}",
            "=" * 76,
            f"  {'Array size':>15}  {'Memory':>8}  {'ns/call':>10}  "
            f"{'GB/s':>7}  {'GFLOPS':>8}  {'vs NumPy':>10}  Tier",
            "  " + "-" * 66,
        ]
        bytes_per = 8 if precision in ("fp64", "double") else 4
        for b in results:
            mem_mb = b.n_elements * bytes_per / 1e6
            if b.ns_per_call != b.ns_per_call:   # nan
                lines.append(f"  {b.n_elements:>15,}  {'ERROR':>8}")
            else:
                tier = ("L1 " if b.n_elements <= 8_192 else
                        "L2 " if b.n_elements <= 131_072 else
                        "L3 " if b.n_elements <= 8_388_608 else "DRAM")
                lines.append(
                    f"  {b.n_elements:>15,}  {mem_mb:>6.1f}MB  "
                    f"{b.ns_per_call:>10.1f}  "
                    f"{b.gb_per_sec:>7.2f}  "
                    f"{b.gflops:>8.2f}  "
                    f"{b.speedup_vs_numpy:>9.1f}x  "
                    f"[{tier}]"
                )
        lines.append("=" * 76)
        report = "\n".join(lines)
        print(report)
        return report

    def inspect(self, result: BackendResult) -> str:
        """Return a detailed inspection report of a compiled BackendResult."""
        extra = result.extra
        lines = [
            "=" * 68,
            "  Poema CNativeEngine — Compiled Artifact Inspection",
            "=" * 68,
            f"  Backend     : {result.backend_name}",
            f"  FMA depth   : {result.fma_count}",
            f"  Epsilon     : {result.epsilon_bound:.3e}",
            f"  Lib path    : {result.emitted_path}",
            f"  Compiler    : {extra.get('compiler', '?')}",
            f"  SIMD level  : {extra.get('simd_level', '?').upper()}",
            f"  AVX2        : {extra.get('has_avx2', False)}",
            f"  AVX-512     : {extra.get('has_avx512', False)}",
            f"  OpenMP      : {extra.get('has_openmp', False)}",
            "  " + "-" * 66,
        ]
        if result.emitted_code:
            c_lines = result.emitted_code.splitlines()
            preview = c_lines[:50]
            lines += ["  C source preview (first 50 lines):", "  " + "-" * 66]
            for ln in preview:
                lines.append("  " + ln)
            if len(c_lines) > 50:
                lines.append(f"  ... ({len(c_lines)} total lines in source)")
        lines.append("=" * 68)
        return "\n".join(lines)

    def get_build_info(self) -> str:
        """Return formatted string describing the detected build environment."""
        import platform as _pl
        cpu = "unknown"
        try:
            with open("/proc/cpuinfo") as f:
                for line in f:
                    if "model name" in line:
                        cpu = line.split(":", 1)[1].strip()
                        break
        except Exception:
            cpu = _pl.processor() or "unknown"
        return (
            f"Poema CNativeEngine Build Info\n"
            f"  Platform   : {_pl.system()} {_pl.machine()} {_pl.release()}\n"
            f"  CPU        : {cpu}\n"
            f"  Compiler   : {self._compiler}\n"
            f"  AVX2       : {self._caps.has_avx2}\n"
            f"  AVX-512    : {self._caps.has_avx512}\n"
            f"  OpenMP     : {self._caps.has_openmp}\n"
            f"  cffi       : {self._caps.has_cffi}\n"
            f"  Build dir  : {self._build_dir}\n"
        )
